void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim){
  if (htim->Instance == TIM2) {
    uint16_t timer_reading = (uint16_t)HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);
    uint8_t timer_upper = (uint8_t) (timer_reading >> 8) & 0xFF;
    uint8_t timer_lower = (uint8_t) (timer_reading & 0xFF);
    sensor_bytes[0] = timer_upper;
    sensor_bytes[1] = timer_lower;
    HAL_I2C_Mem_Read_DMA(&hi2c1, IMU_DEV_ADDR, 0x3B, I2C_MEMADD_SIZE_8BIT, &sensor_bytes[2], 14);
  }
}

void HAL_I2C_MemRxCpltCallback(I2C_HandleTypeDef *hi2c){
  if (hi2c == &hi2c1 && imuTaskHandle != NULL){
    osThreadFlagsSet(imuTaskHandle, FLAG_DMA_COMPLETE);
  }
}

